"""Plans for the operations that change the system.

Everything here only BUILDS command lines. Nothing in this module executes them:
execution is decided by cli.py after the safety checks (--yes, administrator, ...).
"""

import json
import os
import re
import shutil
from dataclasses import dataclass
from typing import Callable, List, Optional

from .devices import UsbDevice

# libwdi driver type numbers (wdi-simple -t). 'usbser' (CDC) only works if the
# wdi-simple build embeds it. Untested here.
DRIVERS = {"winusb": 0, "libusb-win32": 1, "libusbk": 2, "usbser": 3}

# Windows service name -> usbdrv driver name (used by 'reinstall')
SERVICE_TO_DRIVER = {"winusb": "winusb", "libusb0": "libusb-win32", "libusbk": "libusbk", "usbser": "usbser"}

# Device classes whose driver you almost certainly do not want to replace by accident.
PROTECTED_CLASSES = {"HIDClass", "Keyboard", "Mouse", "Bluetooth", "DiskDrive", "CDROM", "WPD"}

# Services that identify a driver put there by libwdi.
LIBWDI_SERVICES = {"winusb", "libusbk", "libusb0"}

CERT_MARK = "(libwdi autogenerated)"
CERT_STORES = ("Root", "TrustedPublisher")

OEM_INF_RE = re.compile(r"^oem\d+\.inf$", re.IGNORECASE)
THUMB_RE = re.compile(r"^[0-9A-Fa-f]{40}$")

CERT_LIST_SCRIPT = r"""
$ErrorActionPreference = 'SilentlyContinue'
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
# The .NET store API is used on purpose, not the certificate PSDrive: a 'powershell' started from PowerShell 7
# (inherited PSModulePath) does not load that drive and the listing came out empty.
$rows = @(foreach ($s in 'Root','TrustedPublisher') {
  $st = New-Object System.Security.Cryptography.X509Certificates.X509Store($s, 'LocalMachine')
  $st.Open('ReadOnly')
  foreach ($c in $st.Certificates) {
    if ($c.Subject -like '*%s*') {
      [pscustomobject]@{ Store = $s; Thumbprint = $c.Thumbprint; Subject = $c.Subject; NotAfter = $c.NotAfter.ToString('s') }
    }
  }
  $st.Close()
})
ConvertTo-Json -InputObject $rows -Compress
""" % CERT_MARK


CERT_REMOVE_SCRIPT = (
    "$st = New-Object System.Security.Cryptography.X509Certificates.X509Store('%s', 'LocalMachine'); "
    "$st.Open('ReadWrite'); "
    "try { $c = @($st.Certificates | Where-Object { $_.Thumbprint -eq '%s' }); "
    "if ($c.Count -eq 0) { throw 'LocalMachine\\%s\\%s: certificate not found' }; $st.Remove($c[0]) } "
    "finally { $st.Close() }")


@dataclass(frozen=True)
class Cert:
    store: str
    thumbprint: str
    subject: str
    not_after: str

INSTANCE_SAFE_RE = re.compile(r"^[\w&.\\{}-]+$")
FILTER_SERVICE = "libusb0"


def filters_query_command(dev: UsbDevice) -> List[str]:
    """Read-only: the UpperFilters of one device (a libusb-win32 'install --filter' adds 'libusb0' there)."""
    if not INSTANCE_SAFE_RE.match(dev.instance_id):
        raise ValueError("unexpected characters in the instance ID: %r" % dev.instance_id)
    script = ("$ErrorActionPreference = 'SilentlyContinue'; "
              "ConvertTo-Json -InputObject @((Get-PnpDeviceProperty -InstanceId '%s' "
              "-KeyName DEVPKEY_Device_UpperFilters).Data) -Compress" % dev.instance_id)
    return ["powershell", "-NoProfile", "-NonInteractive", "-Command", script]


def upper_filters(run: Callable, dev: UsbDevice) -> List[str]:
    res = run(filters_query_command(dev))
    text = (res.stdout or "").strip()
    if res.returncode != 0 or not text:
        return []
    data = json.loads(text)
    return [str(f) for f in data if f] if isinstance(data, list) else ([str(data)] if data else [])


def filter_removal_commands(dev: UsbDevice, filters: List[str]) -> List[List[str]]:
    """Take 'libusb0' out of the device's UpperFilters (other filters are kept) and restart the device."""
    if not INSTANCE_SAFE_RE.match(dev.instance_id):
        raise ValueError("unexpected characters in the instance ID: %r" % dev.instance_id)
    keep = [f for f in filters if f.lower() != FILTER_SERVICE]
    key = "HKLM:\\SYSTEM\\CurrentControlSet\\Enum\\%s" % dev.instance_id
    if keep:
        script = "Set-ItemProperty -LiteralPath '%s' -Name UpperFilters -Value ([string[]]@(%s))" % (
            key, ",".join("'%s'" % f.replace("'", "''") for f in keep))
    else:
        script = "Remove-ItemProperty -LiteralPath '%s' -Name UpperFilters" % key
    return [["powershell", "-NoProfile", "-NonInteractive", "-Command", script],
            ["pnputil", "/restart-device", dev.instance_id]]


def find_wdi(explicit: Optional[str], env: dict, base_dir: str) -> Optional[str]:
    """Locate wdi-simple.exe: --wdi / config, $USBDRV_WDI, PATH, <project>/build/."""
    for cand in (explicit, env.get("USBDRV_WDI")):
        if cand:
            return cand if os.path.isfile(cand) else None
    on_path = shutil.which("wdi-simple") or shutil.which("wdi-simple.exe")
    if on_path:
        return on_path
    local = os.path.join(base_dir, "build", "wdi-simple.exe")
    return local if os.path.isfile(local) else None


def check_protected(dev: UsbDevice) -> Optional[str]:
    if dev.cls in PROTECTED_CLASSES:
        return ("%s is in class '%s' (input/storage/radio): replacing its driver can disable "
                "your keyboard, mouse, disk or Bluetooth. Use --force if you really mean it." % (dev.vidpid, dev.cls))
    return None


def driver_for_reinstall(dev: UsbDevice) -> str:
    """The driver 'reinstall' would put back: the one currently bound, if it is one of ours."""
    drv = SERVICE_TO_DRIVER.get(dev.service.lower())
    if not drv:
        raise ValueError("cannot reinstall: current driver '%s' is not WinUSB/libusbK/libusb-win32/usbser; "
                         "use 'install --driver ...' instead" % (dev.service or "none"))
    return drv


def clean_name(name: str) -> str:
    return re.sub(r"[^\w .()-]", "_", name or "USB device").strip()[:60] or "USB device"


def install_command(wdi: str, dev: UsbDevice, driver: str, dest: str, *, name: Optional[str] = None,
                    wcid: bool = False, silent: bool = False, timeout_ms: Optional[int] = None,
                    filter_driver: bool = False, log_level: int = 3) -> List[str]:
    """Command line for wdi-simple (libwdi). Replaces the driver of ONE interface/device.

    NOTE: stock wdi-simple always self-signs the catalog and adds the certificate to the
    Root and TrustedPublisher stores, even for extract-only. usbdrv never calls it with -x.
    """
    cmd = [wdi, "-n", clean_name(name or dev.name), "-f", "usbdrv.inf",
           "-v", "0x%04X" % dev.vid, "-p", "0x%04X" % dev.pid,
           "-t", str(DRIVERS[driver]), "-d", dest, "-l", str(log_level)]
    if dev.mi is not None:
        cmd += ["-i", str(dev.mi)]
    if wcid:
        cmd.append("-w")
    if filter_driver:
        cmd.append("--filter")
    if silent:
        cmd.append("-s")
    if timeout_ms is not None:
        cmd += ["-o", str(timeout_ms)]
    return cmd


def is_libwdi_package(dev: UsbDevice) -> bool:
    """True if the device is bound to an OEM package published by libwdi (what this tool installs)."""
    return bool(OEM_INF_RE.match(dev.inf_path or "")) and (dev.provider or "").strip().lower() == "libwdi"


def restore_plan(dev: UsbDevice, all_devices: List[UsbDevice], force: bool = False) -> List[List[str]]:
    """Commands to remove the driver package bound to dev and let Windows re-detect it.

    Raises ValueError if it is unsafe: package not an OEM one, not a libwdi driver,
    or used by other present devices too.
    """
    inf = dev.inf_path
    if not OEM_INF_RE.match(inf or ""):
        raise ValueError("the driver of %s (%s) is not an OEM package (inf='%s'): nothing to remove"
                         % (dev.vidpid, dev.instance_id, inf or "-"))
    # a libwdi package is recognised by its provider too: an 'install --driver usbser' leaves service 'usbser'
    if dev.service.lower() not in LIBWDI_SERVICES and not is_libwdi_package(dev) and not force:
        raise ValueError("service '%s' is not WinUSB/libusbK/libusb0 and the package was not published by libwdi, "
                         "so it was probably not installed by this tool. Use --force to remove it anyway."
                         % (dev.service or "-"))
    others = [d.instance_id for d in all_devices
              if d.instance_id != dev.instance_id and d.inf_path.lower() == inf.lower()]
    if others:
        raise ValueError("package %s is also used by: %s. Refusing to remove it." % (inf, ", ".join(others)))
    return [["pnputil", "/delete-driver", inf, "/uninstall", "/force"],
            ["pnputil", "/scan-devices"]]


def list_certs(run: Callable) -> List[Cert]:
    res = run(["powershell", "-NoProfile", "-NonInteractive", "-Command", CERT_LIST_SCRIPT])
    if res.returncode != 0:
        raise RuntimeError("certificate listing failed: %s" % (res.stderr or "").strip())
    text = (res.stdout or "").strip()
    data = json.loads(text) if text else []
    if isinstance(data, dict):
        data = [data]
    return [Cert(r["Store"], r["Thumbprint"].upper(), r["Subject"], r.get("NotAfter") or "") for r in data]


def cert_removal_commands(certs: List[Cert], thumbprint: str) -> List[List[str]]:
    """Commands removing one libwdi certificate (by thumbprint) from the stores where it is found."""
    if not THUMB_RE.match(thumbprint):
        raise ValueError("invalid thumbprint: expected 40 hex digits")
    tp = thumbprint.upper()
    hits = [c for c in certs if c.thumbprint == tp]
    if not hits:
        raise ValueError("no certificate with that thumbprint among the libwdi ones (nothing removed)")
    return [["powershell", "-NoProfile", "-NonInteractive", "-Command",
             CERT_REMOVE_SCRIPT % (c.store, c.thumbprint, c.store, c.thumbprint)]
            for c in hits]
