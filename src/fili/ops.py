# Numeri dei tipi di driver libwdi (wdi-simple -t). 'usbser' (CDC) funziona solo se la
# build di wdi-simple lo include. Non provato qui.
DRIVERS = {"winusb": 0, "libusb-win32": 1, "libusbk": 2, "usbser": 3}

# Nome del servizio Windows -> nome del driver fili (usato da 'reinstall')
SERVICE_TO_DRIVER = {"winusb": "winusb", "libusb0": "libusb-win32", "libusbk": "libusbk", "usbser": "usbser"}

# Classi di dispositivi di cui quasi certamente non si vuole sostituire il driver per errore.
PROTECTED_CLASSES = {"HIDClass", "Keyboard", "Mouse", "Bluetooth", "DiskDrive", "CDROM", "WPD"}

# Servizi che identificano un driver installato da libwdi.
LIBWDI_SERVICES = {"winusb", "libusbk", "libusb0"}

CERT_MARK = "(libwdi autogenerated)"
CERT_STORES = ("Root", "TrustedPublisher")

OEM_INF_RE = re.compile(r"^oem\d+\.inf$", re.IGNORECASE)
THUMB_RE = re.compile(r"^[0-9A-Fa-f]{40}$")

CERT_LIST_SCRIPT = r"""
$ErrorActionPreference = 'SilentlyContinue'
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
# The .NET store API is used on purpose, not the certificate PSDrive: a 'powershell' started from PowerShell 7
# (inherited PSModulePath) does not load that drive and the listing came out empty.
$rows = @(foreach ($s in 'Root','TrustedPublisher') {
  $st = New-Object System.Security.Cryptography.X509Certificates.X509Store($s, 'LocalMachine')
  $st.Open('ReadOnly')
  foreach ($c in $st.Certificates) {
    if ($c.Subject -like '*%s*') {
      [pscustomobject]@{ Store = $s; Thumbprint = $c.Thumbprint; Subject = $c.Subject; NotAfter = $c.NotAfter.ToString('s') }
    }
  }
  $st.Close()
})
ConvertTo-Json -InputObject $rows -Compress
""" % CERT_MARK


CERT_REMOVE_SCRIPT = (
    "$st = New-Object System.Security.Cryptography.X509Certificates.X509Store('%s', 'LocalMachine'); "
    "$st.Open('ReadWrite'); "
    "try { $c = @($st.Certificates | Where-Object { $_.Thumbprint -eq '%s' }); "
    "if ($c.Count -eq 0) { throw 'LocalMachine\\%s\\%s: certificate not found' }; $st.Remove($c[0]) } "
    "finally { $st.Close() }")


@dataclass(frozen=True)
class Cert:
    store: str
    thumbprint: str
    subject: str
    not_after: str

INSTANCE_SAFE_RE = re.compile(r"^[\w&.\\{}-]+$")
FILTER_SERVICE = "libusb0"


def filters_query_command(dev: UsbDevice) -> List[str]:
    """Sola lettura: gli UpperFilters di un dispositivo (un 'install --filter' di libusb-win32 vi aggiunge 'libusb0')."""
    if not INSTANCE_SAFE_RE.match(dev.instance_id):
        raise ValueError("unexpected characters in the instance ID: %r" % dev.instance_id)
    script = ("$ErrorActionPreference = 'SilentlyContinue'; "
              "ConvertTo-Json -InputObject @((Get-PnpDeviceProperty -InstanceId '%s' "
              "-KeyName DEVPKEY_Device_UpperFilters).Data) -Compress" % dev.instance_id)
    return ["powershell", "-NoProfile", "-NonInteractive", "-Command", script]


def upper_filters(run: Callable, dev: UsbDevice) -> List[str]:
    res = run(filters_query_command(dev))
    text = (res.stdout or "").strip()
    if res.returncode != 0 or not text:
        return []
    data = json.loads(text)
    return [str(f) for f in data if f] if isinstance(data, list) else ([str(data)] if data else [])


def filter_removal_commands(dev: UsbDevice, filters: List[str]) -> List[List[str]]:
    """Toglie 'libusb0' dagli UpperFilters del dispositivo (gli altri filtri restano) e riavvia il dispositivo."""
    if not INSTANCE_SAFE_RE.match(dev.instance_id):
        raise ValueError("unexpected characters in the instance ID: %r" % dev.instance_id)
    keep = [f for f in filters if f.lower() != FILTER_SERVICE]
    key = "HKLM:\\SYSTEM\\CurrentControlSet\\Enum\\%s" % dev.instance_id
    if keep:
        script = "Set-ItemProperty -LiteralPath '%s' -Name UpperFilters -Value ([string[]]@(%s))" % (
            key, ",".join("'%s'" % f.replace("'", "''") for f in keep))
    else:
        script = "Remove-ItemProperty -LiteralPath '%s' -Name UpperFilters" % key
    return [["powershell", "-NoProfile", "-NonInteractive", "-Command", script],
            ["pnputil", "/restart-device", dev.instance_id]]


def find_wdi(explicit: Optional[str], env: dict, base_dir: str) -> Optional[str]:
    """Trova wdi-simple.exe: --wdi / config, $FILI_WDI, PATH, accanto all'eseguibile (versione compilata), <progetto>/build/."""
    for cand in (explicit, env.get("FILI_WDI")):
        if cand:
            return cand if os.path.isfile(cand) else None
    on_path = shutil.which("wdi-simple") or shutil.which("wdi-simple.exe")
    if on_path:
        return on_path
    candidates = [os.path.join(base_dir, "build", "wdi-simple.exe")]
    if getattr(sys, "frozen", False):
        candidates.insert(0, os.path.join(os.path.dirname(sys.executable), "wdi-simple.exe"))
    return next((c for c in candidates if os.path.isfile(c)), None)


def check_protected(dev: UsbDevice) -> Optional[str]:
    if dev.cls in PROTECTED_CLASSES:
        return ("%s is in class '%s' (input/storage/radio): replacing its driver can disable "
                "your keyboard, mouse, disk or Bluetooth. Use --force if you really mean it." % (dev.vidpid, dev.cls))
    return None


def driver_for_reinstall(dev: UsbDevice) -> str:
    """Il driver che 'reinstall' rimetterebbe: quello attualmente associato, se è uno dei nostri."""
    drv = SERVICE_TO_DRIVER.get(dev.service.lower())
    if not drv:
        raise ValueError("cannot reinstall: current driver '%s' is not WinUSB/libusbK/libusb-win32/usbser; "
                         "use 'install --driver ...' instead" % (dev.service or "none"))
    return drv


def clean_name(name: str) -> str:
    return re.sub(r"[^\w .()-]", "_", name or "USB device").strip()[:60] or "USB device"


def siblings(dev: UsbDevice, all_devices: List[UsbDevice]) -> List[UsbDevice]:
    """Gli ALTRI dispositivi presenti con lo stesso VID/PID (e interfaccia): wdi-simple li cambia tutti insieme a dev."""
    return [d for d in all_devices
            if d.instance_id.lower() != dev.instance_id.lower()
            and d.vid == dev.vid and d.pid == dev.pid and d.mi == dev.mi]


def install_command(wdi: str, dev: UsbDevice, driver: str, dest: str, *, name: Optional[str] = None,
                    wcid: bool = False, silent: bool = False, timeout_ms: Optional[int] = None,
                    filter_driver: bool = False, log_level: int = 3, extract_only: bool = False) -> List[str]:
    """Riga di comando per wdi-simple (libwdi). Sostituisce il driver di UNA interfaccia/dispositivo.

    NOTA: il wdi-simple originale autofirma sempre il catalogo e aggiunge il certificato agli archivi
    Root e TrustedPublisher, anche con la sola estrazione (-x). Senza -x installa il driver su TUTTI i
    dispositivi presenti con lo stesso VID/PID: per sceglierne uno solo usare extract_only=True e poi
    stage_command() + bind_command().
    """
    cmd = [wdi, "-n", clean_name(name or dev.name), "-f", "fili.inf",
           "-v", "0x%04X" % dev.vid, "-p", "0x%04X" % dev.pid,
           "-t", str(DRIVERS[driver]), "-d", dest, "-l", str(log_level)]
    if dev.mi is not None:
        cmd += ["-i", str(dev.mi)]
    if wcid:
        cmd.append("-w")
    if filter_driver:
        cmd.append("--filter")
    if silent:
        cmd.append("-s")
    if timeout_ms is not None:
        cmd += ["-o", str(timeout_ms)]
    if extract_only:
        cmd.append("-x")
    return cmd


PUBLISHED_RE = re.compile(r"\boem\d+\.inf\b", re.IGNORECASE)

# DiInstallDevice installa un driver su UN dispositivo (a differenza di pnputil /add-driver /install e di
# UpdateDriverForPlugAndPlayDevices, che aggiornano tutti i dispositivi con quell'ID hardware). Il pacchetto è già
# nell'archivio driver (pnputil /add-driver): DI_ENUMSINGLEINF limita l'elenco dei driver compatibili a quell'INF,
# quindi non può vincere un altro pacchetto con lo stesso ID hardware.
BIND_CSHARP = r"""
using System;
using System.Runtime.InteropServices;
public static class FiliBind {
  [StructLayout(LayoutKind.Sequential)]
  struct DevInfoData { public int cbSize; public Guid ClassGuid; public int DevInst; public IntPtr Reserved; }
  [StructLayout(LayoutKind.Sequential, Pack = 1, CharSet = CharSet.Unicode)]
  struct DrvInfoData {
    public int cbSize; public int DriverType; public IntPtr Reserved;
    [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 256)] public string Description;
    [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 256)] public string MfgName;
    [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 256)] public string ProviderName;
    public long DriverDate; public ulong DriverVersion;
  }
  [StructLayout(LayoutKind.Sequential, CharSet = CharSet.Unicode)]
  struct InstallParams {
    public int cbSize; public int Flags; public int FlagsEx; public IntPtr hwndParent;
    public IntPtr InstallMsgHandler; public IntPtr InstallMsgHandlerContext; public IntPtr FileQueue;
    public IntPtr ClassInstallReserved; public int Reserved;
    [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 260)] public string DriverPath;
  }
  [DllImport("setupapi.dll", SetLastError = true)] static extern IntPtr SetupDiCreateDeviceInfoList(IntPtr g, IntPtr h);
  [DllImport("setupapi.dll", SetLastError = true)] static extern bool SetupDiDestroyDeviceInfoList(IntPtr s);
  [DllImport("setupapi.dll", SetLastError = true, CharSet = CharSet.Unicode)]
  static extern bool SetupDiOpenDeviceInfoW(IntPtr s, string id, IntPtr h, int f, ref DevInfoData d);
  [DllImport("setupapi.dll", SetLastError = true, CharSet = CharSet.Unicode)]
  static extern bool SetupDiGetDeviceInstallParamsW(IntPtr s, ref DevInfoData d, ref InstallParams p);
  [DllImport("setupapi.dll", SetLastError = true, CharSet = CharSet.Unicode)]
  static extern bool SetupDiSetDeviceInstallParamsW(IntPtr s, ref DevInfoData d, ref InstallParams p);
  [DllImport("setupapi.dll", SetLastError = true)]
  static extern bool SetupDiBuildDriverInfoList(IntPtr s, ref DevInfoData d, int type);
  [DllImport("setupapi.dll", SetLastError = true, CharSet = CharSet.Unicode)]
  static extern bool SetupDiEnumDriverInfoW(IntPtr s, ref DevInfoData d, int type, int idx, ref DrvInfoData i);
  [DllImport("newdev.dll", SetLastError = true)]
  static extern bool DiInstallDevice(IntPtr hwnd, IntPtr s, ref DevInfoData d, ref DrvInfoData i, int flags, out bool reboot);

  static string Code() {
    int e = Marshal.GetLastWin32Error();
    return "0x" + e.ToString("X8") + (e == unchecked((int)0xE000020B) ? ", device no longer present" : "");
  }
  static void Fail(string what) {
    throw new Exception(what + " failed (error " + Code() + ")");
  }
  public static string Run(string instanceId, string infPath) {
    IntPtr set = SetupDiCreateDeviceInfoList(IntPtr.Zero, IntPtr.Zero);
    if (set == (IntPtr)(-1)) Fail("SetupDiCreateDeviceInfoList");
    try {
      var dev = new DevInfoData(); dev.cbSize = Marshal.SizeOf(typeof(DevInfoData));
      if (!SetupDiOpenDeviceInfoW(set, instanceId, IntPtr.Zero, 0, ref dev)) Fail("SetupDiOpenDeviceInfo");
      var prm = new InstallParams(); prm.cbSize = Marshal.SizeOf(typeof(InstallParams));
      if (!SetupDiGetDeviceInstallParamsW(set, ref dev, ref prm)) Fail("SetupDiGetDeviceInstallParams");
      prm.Flags |= 0x00010000;   // DI_ENUMSINGLEINF
      prm.DriverPath = infPath;
      if (!SetupDiSetDeviceInstallParamsW(set, ref dev, ref prm)) Fail("SetupDiSetDeviceInstallParams");
      if (!SetupDiBuildDriverInfoList(set, ref dev, 2)) Fail("SetupDiBuildDriverInfoList");   // SPDIT_COMPATDRIVER
      var drv = new DrvInfoData(); drv.cbSize = Marshal.SizeOf(typeof(DrvInfoData));
      if (!SetupDiEnumDriverInfoW(set, ref dev, 2, 0, ref drv))
        throw new Exception("no driver in " + infPath + " matches this device (error " + Code() + ")");
      bool reboot;
      if (!DiInstallDevice(IntPtr.Zero, set, ref dev, ref drv, 0, out reboot)) Fail("DiInstallDevice");
      return "installed '" + drv.Description + "' (" + drv.ProviderName + ") on " + instanceId + (reboot ? "; reboot required" : "");
    } finally { SetupDiDestroyDeviceInfoList(set); }
  }
}
"""


def stage_command(inf: str) -> List[str]:
    """Mette il pacchetto nell'archivio driver SENZA associarlo a nessun dispositivo (niente /install)."""
    return ["pnputil", "/add-driver", inf]


def published_name(output: str) -> Optional[str]:
    """Il nome 'oemNN.inf' con cui pnputil ha pubblicato il pacchetto (l'output è localizzato: si cerca solo il nome)."""
    m = PUBLISHED_RE.search(output or "")
    return m.group(0).lower() if m else None


def bind_command(dev: UsbDevice, published: str, windir: str) -> List[str]:
    """Installa il pacchetto già nell'archivio driver su UN SOLO dispositivo (per instance ID)."""
    if not INSTANCE_SAFE_RE.match(dev.instance_id):
        raise ValueError("unexpected characters in the instance ID: %r" % dev.instance_id)
    if not OEM_INF_RE.match(published):
        raise ValueError("unexpected published package name: %r" % published)
    inf = os.path.join(windir, "INF", published).replace("'", "''")   # windir viene dall'ambiente: niente apici liberi
    script = ("$ErrorActionPreference = 'Stop'; $ProgressPreference = 'SilentlyContinue'\n"
              "try {\n"
              "  Add-Type -TypeDefinition @'\n%s'@\n"
              "  [FiliBind]::Run('%s', '%s')\n"
              "} catch {\n"
              "  $e = $_.Exception; while ($e.InnerException) { $e = $e.InnerException }\n"
              "  [Console]::Error.WriteLine($e.Message); exit 1\n"
              "}\n"
              % (BIND_CSHARP, dev.instance_id, inf))
    encoded = base64.b64encode(script.encode("utf-16-le")).decode("ascii")
    return ["powershell", "-NoProfile", "-NonInteractive", "-OutputFormat", "Text", "-EncodedCommand", encoded]


def is_libwdi_package(dev: UsbDevice) -> bool:
    """True se il dispositivo è associato a un pacchetto OEM del tipo che questo strumento installa.

    Il provider è 'libwdi' per WinUSB e usbser, ma 'libusbK' / 'libusb-win32' per quei driver, quindi conta
    anche il servizio (winusb, libusbk, libusb0).
    """
    if not OEM_INF_RE.match(dev.inf_path or ""):
        return False
    return (dev.provider or "").strip().lower() == "libwdi" or (dev.service or "").lower() in LIBWDI_SERVICES


def restore_plan(dev: UsbDevice, all_devices: List[UsbDevice], force: bool = False,
                 all_matching: bool = False) -> List[List[str]]:
    """Comandi per rimuovere il pacchetto driver associato a dev e lasciare che Windows lo rilevi di nuovo.

    Solleva ValueError se non è sicuro: pacchetto non OEM, non di un driver libwdi,
    oppure usato anche da altri dispositivi presenti. Con all_matching il pacchetto condiviso si rimuove solo
    se gli altri dispositivi che lo usano sono tutti gemelli di dev (stesso VID/PID/interfaccia): è il caso
    di 'install --all-matching', che li lega tutti allo stesso pacchetto.
    """
    inf = dev.inf_path
    if not OEM_INF_RE.match(inf or ""):
        raise ValueError("the driver of %s (%s) is not an OEM package (inf='%s'): nothing to remove"
                         % (dev.vidpid, dev.instance_id, inf or "-"))
    # un pacchetto libwdi si riconosce anche dal provider: un 'install --driver usbser' lascia il servizio 'usbser'
    if dev.service.lower() not in LIBWDI_SERVICES and not is_libwdi_package(dev) and not force:
        raise ValueError("service '%s' is not WinUSB/libusbK/libusb0 and the package was not published by libwdi, "
                         "so it was probably not installed by this tool. Use --force to remove it anyway."
                         % (dev.service or "-"))
    others = [d.instance_id for d in all_devices
              if d.instance_id != dev.instance_id and d.inf_path.lower() == inf.lower()]
    if others:
        twins = {d.instance_id.lower() for d in siblings(dev, all_devices)}
        strangers = [i for i in others if i.lower() not in twins]
        if strangers or not all_matching:
            hint = ""
            if not strangers:
                hint = " They are identical to this one: if 'install --all-matching' put them there, use 'restore --all-matching'."
            raise ValueError("package %s is also used by: %s. Refusing to remove it.%s"
                             % (inf, ", ".join(strangers or others), hint))
    return [["pnputil", "/delete-driver", inf, "/uninstall", "/force"],
            ["pnputil", "/scan-devices"]]


def list_certs(run: Callable) -> List[Cert]:
    res = run(["powershell", "-NoProfile", "-NonInteractive", "-Command", CERT_LIST_SCRIPT])
    if res.returncode != 0:
        raise RuntimeError("certificate listing failed: %s" % (res.stderr or "").strip())
    text = (res.stdout or "").strip()
    data = json.loads(text) if text else []
    if isinstance(data, dict):
        data = [data]
    return [Cert(r["Store"], r["Thumbprint"].upper(), r["Subject"], r.get("NotAfter") or "") for r in data]


def cert_removal_commands(certs: List[Cert], thumbprint: str) -> List[List[str]]:
    """Comandi che rimuovono un certificato libwdi (tramite thumbprint) dagli archivi in cui si trova."""
    if not THUMB_RE.match(thumbprint):
        raise ValueError("invalid thumbprint: expected 40 hex digits")
    tp = thumbprint.upper()
    hits = [c for c in certs if c.thumbprint == tp]
    if not hits:
        raise ValueError("no certificate with that thumbprint among the libwdi ones (nothing removed)")
    return [["powershell", "-NoProfile", "-NonInteractive", "-Command",
             CERT_REMOVE_SCRIPT % (c.store, c.thumbprint, c.store, c.thumbprint)]
            for c in hits]


# --- usb-reset: recupero di un dispositivo (o del suo hub) che non risponde -------------------------------------------
#
# Windows non ha un servizio USB da riavviare: la pila USB è fatta di driver di controller e di hub. Quello che si può
# fare dal di fuori è fermare i comandi di sistema rimasti appesi su quel dispositivo e disattivare e riattivare il
# dispositivo (o l'hub a cui è collegato, con --hub). Il controller (e l'hub radice) non si toccano mai: il suo riavvio
# staccherebbe anche tastiera e mouse USB.

STUCK_AFTER_S = 30      # un pnputil che lavora sul dispositivo da più di tanti secondi è considerato appeso
HUB_SERVICES = {"usbhub", "usbhub3", "usbhub4"}
MAX_DEPTH = 3           # quanti livelli sotto un hub si guardano per trovare dispositivi protetti

STUCK_SCRIPT = r"""# fili:stuck
$ErrorActionPreference = 'SilentlyContinue'
$id = '%s'
$rows = @(Get-CimInstance Win32_Process -Filter "Name='pnputil.exe'" | Where-Object {
    $_.CommandLine -and $_.CommandLine.IndexOf($id, [StringComparison]::OrdinalIgnoreCase) -ge 0 } |
  ForEach-Object { [pscustomobject]@{ Pid = [int]$_.ProcessId; Command = [string]$_.CommandLine
                                      Seconds = [int]((Get-Date) - $_.CreationDate).TotalSeconds } })
ConvertTo-Json -InputObject $rows -Compress
"""

PARENTS_SCRIPT = r"""# fili:parents
$ErrorActionPreference = 'SilentlyContinue'
$cur = '%s'
$out = @()
for ($i = 0; $i -lt 6; $i++) {
  $p = (Get-PnpDeviceProperty -InstanceId $cur -KeyName 'DEVPKEY_Device_Parent').Data
  if (-not $p) { break }
  $d = Get-PnpDevice -InstanceId $p
  $out += [pscustomobject]@{ InstanceId = [string]$p; Class = [string]$d.Class; Name = [string]$d.FriendlyName
                             Service = [string](Get-PnpDeviceProperty -InstanceId $p -KeyName 'DEVPKEY_Device_Service').Data }
  $cur = $p
}
ConvertTo-Json -InputObject @($out) -Compress
"""

DESCENDANTS_SCRIPT = r"""# fili:descendants
$ErrorActionPreference = 'SilentlyContinue'
$rows = New-Object System.Collections.ArrayList
function Walk($id, $depth) {
  if ($depth -gt %d) { return }
  $kids = (Get-PnpDeviceProperty -InstanceId $id -KeyName 'DEVPKEY_Device_Children').Data
  foreach ($k in @($kids)) {
    if (-not $k) { continue }
    $d = Get-PnpDevice -InstanceId $k -PresentOnly
    if (-not $d) { continue }
    [void]$rows.Add([pscustomobject]@{ InstanceId = [string]$k; Class = [string]$d.Class; Name = [string]$d.FriendlyName })
    Walk $k ($depth + 1)
  }
}
Walk '%s' 1
ConvertTo-Json -InputObject @($rows) -Compress
"""


def _check_instance_id(instance_id: str) -> str:
    if not INSTANCE_SAFE_RE.match(instance_id):
        raise ValueError("unexpected characters in the instance ID: %r" % instance_id)
    return instance_id


def _json_rows(text: str) -> List[dict]:
    text = (text or "").strip()
    if not text:
        return []
    data = json.loads(text)
    return [data] if isinstance(data, dict) else [r for r in data if r]


def stuck_command(dev: UsbDevice) -> List[str]:
    return ["powershell", "-NoProfile", "-NonInteractive", "-Command", STUCK_SCRIPT % _check_instance_id(dev.instance_id)]


def find_stuck(run: Callable, dev: UsbDevice) -> List[dict]:
    """Sola lettura: i processi pnputil che hanno questo dispositivo nella riga di comando ({'Pid', 'Command', 'Seconds'})."""
    res = run(stuck_command(dev))
    return _json_rows(res.stdout) if res.returncode == 0 else []


def ancestors(run: Callable, dev: UsbDevice) -> List[dict]:
    """Sola lettura: genitore, nonno... del dispositivo, dal più vicino ({'InstanceId', 'Class', 'Name', 'Service'})."""
    res = run(["powershell", "-NoProfile", "-NonInteractive", "-Command",
               PARENTS_SCRIPT % _check_instance_id(dev.instance_id)])
    return _json_rows(res.stdout) if res.returncode == 0 else []


def descendants(run: Callable, instance_id: str) -> List[dict]:
    """Sola lettura: i dispositivi presenti sotto un hub, fino a MAX_DEPTH livelli ({'InstanceId', 'Class', 'Name'})."""
    res = run(["powershell", "-NoProfile", "-NonInteractive", "-Command",
               DESCENDANTS_SCRIPT % (MAX_DEPTH, _check_instance_id(instance_id))])
    return _json_rows(res.stdout) if res.returncode == 0 else []


def parent_hub(chain: List[dict]) -> Optional[dict]:
    """Il primo antenato che è un hub USB esterno. L'hub radice del controller non vale: non si riavvia mai."""
    for a in chain:
        iid = a.get("InstanceId", "")
        if iid.upper().startswith("USB" + chr(92) + "ROOT_HUB"):
            return None
        if (a.get("Service") or "").lower() in HUB_SERVICES:
            return a
    return None


def protected_below(kids: List[dict]) -> List[dict]:
    """I dispositivi di una classe protetta (tastiera, mouse, dischi, Bluetooth...) tra quelli elencati."""
    return [k for k in kids if k.get("Class") in PROTECTED_CLASSES]


CM_PROB_DISABLED = 22


def restart_plan(dev: UsbDevice) -> List[List[str]]:
    """Riavvio di UN dispositivo: se Windows lo riporta come disattivato (problema 22) lo riattiva, altrimenti lo riavvia.
    Non cambia nessun driver."""
    target = _check_instance_id(dev.instance_id)
    if dev.problem_code == CM_PROB_DISABLED:
        return [["pnputil", "/enable-device", target]]
    return [["pnputil", "/restart-device", target]]


def usb_reset_plan(dev: UsbDevice, stuck: List[dict], hub: Optional[dict] = None,
                   stuck_after: int = STUCK_AFTER_S) -> List[List[str]]:
    """Comandi del recupero: ferma i pnputil appesi su questo dispositivo, poi disattiva e riattiva il dispositivo
    (o il suo hub). I processi più giovani di stuck_after secondi non sono considerati appesi e non si toccano."""
    cmds = []
    for p in stuck:
        if int(p.get("Seconds", 0)) >= stuck_after:
            cmds.append(["taskkill", "/PID", str(int(p["Pid"])), "/F"])
    target = _check_instance_id(hub["InstanceId"] if hub else dev.instance_id)
    cmds.append(["pnputil", "/disable-device", target])
    cmds.append(["pnputil", "/enable-device", target])
    return cmds
