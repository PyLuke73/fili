class TestLogging(unittest.TestCase):
    def tearDown(self):
        logsetup.setup_logging("INFO")   # close file handlers (Windows keeps them locked)

    def _run_failing(self, tmp, fmt):
        log = os.path.join(tmp, "u.log")
        fail = FakeRun(fail={"wdi-simple": (5, "installing...", "driver install failed: access denied")})
        code, out, err, run = call(["--log-file", log, "--log-format", fmt, "install", "--vid", "1234", "--pid", "0001",
                                    "--driver", "winusb", "--wdi", fake_wdi(tmp), "--yes"], run=fail, admin=True)
        logsetup.setup_logging("INFO")
        return code, read_text(log)

    def test_text_log(self):
        with tempfile.TemporaryDirectory() as tmp:
            code, text = self._run_failing(tmp, "text")
            self.assertEqual(code, 6)
            self.assertRegex(text, r"\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} ERROR")
            self.assertIn("driver install failed: access denied", text)
            self.assertIn("exit 5", text)
            self.assertIn("failed (exit 6)", text)
            self.assertNotIn("DEBUG", text)                           # default level INFO

    def test_json_log_is_valid(self):
        with tempfile.TemporaryDirectory() as tmp:
            code, text = self._run_failing(tmp, "json")
            lines = [json.loads(l) for l in text.splitlines()]        # every line must be valid JSON
            self.assertTrue(lines)
            for rec in lines:
                self.assertTrue({"time", "level", "message"} <= set(rec))
            errors = [r for r in lines if r["level"] == "ERROR"]
            self.assertTrue(any(r.get("exit_code") == 5 for r in errors))
            self.assertTrue(any("access denied" in r["message"] for r in errors))
            self.assertTrue(any(r.get("stream") == "stderr" and "access denied" in r["message"] for r in errors),
                            "the tool's own stderr must be logged at ERROR level")

    def test_verbose_logs_commands_and_echoes(self):
        with tempfile.TemporaryDirectory() as tmp:
            log = os.path.join(tmp, "v.log")
            code, out, err, run = call(["list", "--log-file", log, "-v"])
            logsetup.setup_logging("INFO")
            text = read_text(log)
            self.assertIn("DEBUG", text)
            self.assertIn("exec: powershell", text)
            self.assertIn("DEBUG", err)                                # echoed on stderr

    def test_no_environment_or_secrets_logged(self):
        with tempfile.TemporaryDirectory() as tmp:
            log = os.path.join(tmp, "s.log")
            call(["list", "--log-file", log, "--log-level", "DEBUG"], env={"SECRET_TOKEN": "hunter2", "APPDATA": tmp})
            logsetup.setup_logging("INFO")
            self.assertNotIn("hunter2", read_text(log))

    def test_invalid_level(self):
        self.assertEqual(call(["list", "--log-level", "LOUD"])[0], 2)

    def test_output_is_clipped(self):
        self.assertTrue(len(logsetup.clip("x" * 100000)) < 5000)


