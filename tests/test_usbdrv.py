READ_ONLY_MARKERS = ("Get-PnpDevice", "'ReadOnly'", "Get-WinEvent")


class FakeRun:
    """Records every command; answers the read-only PowerShell queries from fixtures."""

    def __init__(self, devices_json=None, fail=None, after=None, after_seq=None):
        self.calls = []
        self.devices_json = devices_json if devices_json is not None else DEVICES
        self.fail = fail or {}        # substring -> (returncode, stdout, stderr)
        self.after = after            # devices JSON returned from the 2nd enumeration on
        self.after_seq = after_seq    # or: one list per enumeration from the 2nd on (the last repeats)
        self.enumerations = 0

    def __call__(self, cmd):
        self.calls.append(list(cmd))
        text = " ".join(cmd)
        for key, (rc, so, se) in self.fail.items():
            if key in text:
                return types.SimpleNamespace(returncode=rc, stdout=so, stderr=se)
        if cmd[0] == "powershell":
            script = cmd[-1]
            if "Get-PnpDevice" in script:
                self.enumerations += 1
                data = self.after if (self.after is not None and self.enumerations > 1) else self.devices_json
                if self.after_seq and self.enumerations > 1:
                    data = self.after_seq[min(self.enumerations - 2, len(self.after_seq) - 1)]
                return types.SimpleNamespace(returncode=0, stdout=json.dumps(data), stderr="")
            if "'ReadOnly'" in script:
                return types.SimpleNamespace(returncode=0, stdout=json.dumps(CERTS), stderr="")
            if "Get-WinEvent" in script:
                return types.SimpleNamespace(returncode=0, stdout="[]", stderr="")
        return types.SimpleNamespace(returncode=0, stdout="ok\n", stderr="")

    def mutating(self):
        """Commands that are not one of the known read-only queries."""
        return [c for c in self.calls
                if not (c[0] == "powershell" and any(m in c[-1] for m in READ_ONLY_MARKERS))]


def call(argv, run=None, admin=False, env=None, **kw):
    run = run or FakeRun()
    out, err = io.StringIO(), io.StringIO()
    code = cli.main(argv, run=run, is_admin=lambda: admin, env=env if env is not None else {},
                    out=out, err=err, **kw)
    return code, out.getvalue(), err.getvalue(), run


def read_text(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write_text(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def fake_wdi(tmp):
    p = os.path.join(tmp, "wdi-simple.exe")
    write_text(p, "")
    return p


class TestParsing(unittest.TestCase):
    def test_hex_ids(self):
        self.assertEqual(devices.parse_hex_id("0483"), 0x483)
        self.assertEqual(devices.parse_hex_id("0x374b"), 0x374B)
        for bad in ("", "xyz", "12345", "0x", "-1"):
            with self.assertRaises(ValueError):
                devices.parse_hex_id(bad)

    def test_parse_list(self):
        devs = devices.parse_device_list(json.dumps(DEVICES))
        self.assertEqual(len(devs), 9)  # root hub skipped
        d = [x for x in devs if x.mi == 0][0]
        self.assertEqual((d.vid, d.pid, d.service, d.driver_version), (0x483, 0x374B, "WinUSB", "10.0.19041.1"))
        self.assertEqual(devices.parse_device_list(""), [])
        one = devices.parse_device_list(json.dumps(DEVICES[3]))  # single object, not a list
        self.assertEqual(len(one), 1)
        self.assertFalse(one[0].has_driver)
        self.assertEqual(one[0].problem_status, 3221225473)

    def test_filters(self):
        devs = devices.parse_device_list(json.dumps(DEVICES))
        self.assertEqual(len(devices.filter_devices(devs)), 8)  # hub hidden by default
        self.assertEqual(len(devices.filter_devices(devs, include_hubs=True)), 9)
        nodrv = devices.filter_devices(devs, only_no_driver=True)
        self.assertEqual([d.vid for d in nodrv], [0x1234])
        noparent = devices.filter_devices(devs, include_parents=False)
        self.assertFalse([d for d in noparent if (d.vid, d.pid, d.mi) == (0x483, 0x374B, None)])

    def test_selection(self):
        devs = devices.parse_device_list(json.dumps(DEVICES))
        self.assertEqual(devices.select_target(devs, 0x483, 0x374B, 0).service, "WinUSB")
        with self.assertRaises(devices.AmbiguousError):
            devices.select_target(devs, 0x483, 0x374B)           # composite, no --iface
        with self.assertRaises(devices.NotFoundError):
            devices.select_target(devs, 0x483, 0x374B, 5)        # bad interface
        with self.assertRaises(devices.NotFoundError):
            devices.select_target(devs, 0x1234, 0x0001, 0)       # not composite
        with self.assertRaises(devices.NotFoundError):
            devices.select_target(devs, 0xDEAD, 0xBEEF)
        with self.assertRaises(devices.AmbiguousError):
            devices.select_target(devs, 0xAAAA, 0x0002)          # two identical
        self.assertEqual(devices.select_target(devs, 0xAAAA, 0x0002, instance="usb\\vid_aaaa&pid_0002\\x2").serial, "X2")
        self.assertEqual(devices.select_target(devs, 0x1234, 0x0001).name, "Unknown device")


class TestExitCodes(unittest.TestCase):
    def test_table(self):
        self.assertEqual(sorted(cli.EXIT_CODES), [0, 1, 2, 3, 4, 5, 6, 7])

    def test_each_code_is_reachable(self):
        with tempfile.TemporaryDirectory() as tmp:
            wdi = fake_wdi(tmp)
            self.assertEqual(call(["list"])[0], 0)
            self.assertEqual(call(["list", "--bogus"])[0], 2)                                      # argparse
            self.assertEqual(call(["status", "--vid", "zz", "--pid", "1"])[0], 2)
            self.assertEqual(call(["install", "--vid", "DEAD", "--pid", "BEEF", "--driver", "winusb", "--yes"], admin=True)[0], 4)
            self.assertEqual(call(["status", "--vid", "AAAA", "--pid", "0002"])[0], 5)
            self.assertEqual(call(["install", "--vid", "1234", "--pid", "0001", "--driver", "winusb", "--wdi", wdi])[0], 7)
            self.assertEqual(call(["install", "--vid", "1234", "--pid", "0001", "--driver", "winusb", "--wdi", wdi, "--yes"])[0], 3)
            fail = FakeRun(fail={"wdi-simple": (5, "", "boom")})
            self.assertEqual(call(["install", "--vid", "1234", "--pid", "0001", "--driver", "winusb", "--wdi", wdi, "--yes"],
                                  run=fail, admin=True)[0], 6)
        broken = FakeRun(fail={"Get-PnpDevice": (1, "", "powershell exploded")})
        self.assertEqual(call(["list"], run=broken)[0], 1)

    def test_documented(self):
        readme = read_text(os.path.join(ROOT, "README.md"))
        for code in range(8):
            self.assertIn("| %d |" % code, readme, "exit code %d missing from README table" % code)


class TestSafety(unittest.TestCase):
    def test_no_yes_no_execution(self):
        with tempfile.TemporaryDirectory() as tmp:
            for argv in (["install", "--vid", "1234", "--pid", "0001", "--driver", "winusb", "--wdi", fake_wdi(tmp)],
                         ["restore", "--vid", "0483", "--pid", "374B", "--iface", "0"],
                         ["cert-remove", "--thumbprint", "A" * 40]):
                code, out, err, run = call(argv, admin=True)
                self.assertEqual(code, 7, argv)
                self.assertEqual(run.mutating(), [], argv)
                self.assertIn("--yes", err)

    def test_dry_run_executes_nothing(self):
        with tempfile.TemporaryDirectory() as tmp:
            for argv in (["install", "--vid", "1234", "--pid", "0001", "--driver", "libusbk", "--wdi", fake_wdi(tmp), "--dry-run", "--yes"],
                         ["reinstall", "--vid", "0483", "--pid", "374B", "--iface", "0", "--wdi", fake_wdi(tmp), "--dry-run", "--yes"],
                         ["restore", "--vid", "0483", "--pid", "374B", "--iface", "0", "--dry-run", "--yes"],
                         ["uninstall", "--vid", "0483", "--pid", "374B", "--iface", "0", "--dry-run"],
                         ["cert-remove", "--thumbprint", "A" * 40, "--dry-run", "--yes"]):
                code, out, err, run = call(argv, admin=True)
                self.assertEqual(code, 0, (argv, err))
                self.assertEqual(run.mutating(), [], argv)
                self.assertIn("[dry-run]", out)

    def test_dry_run_needs_neither_admin_nor_tool(self):
        # hermetic: a wdi-simple.exe built in <project>/build or found on PATH must not change the result
        import shutil
        from unittest import mock
        with tempfile.TemporaryDirectory() as empty,                 mock.patch.object(cli, "_project_dir", return_value=empty),                 mock.patch.object(shutil, "which", return_value=None):
            code, out, err, run = call(["install", "--vid", "1234", "--pid", "0001", "--driver", "winusb", "--dry-run"], admin=False)
        self.assertEqual(code, 0)
        self.assertIn("NOT FOUND", out)

    def test_dry_run_finds_the_exe_in_the_project_build_dir(self):
        import shutil
        from unittest import mock
        with tempfile.TemporaryDirectory() as proj, mock.patch.object(shutil, "which", return_value=None):
            os.makedirs(os.path.join(proj, "build"))
            exe = os.path.join(proj, "build", "wdi-simple.exe")
            open(exe, "wb").write(b"MZ dummy")
            with mock.patch.object(cli, "_project_dir", return_value=proj):
                code, out, err, run = call(["install", "--vid", "1234", "--pid", "0001", "--driver", "winusb", "--dry-run"], admin=False)
        self.assertEqual(code, 0)
        self.assertNotIn("NOT FOUND", out)
        self.assertIn(exe, out)
        self.assertEqual(run.mutating(), [])

    def test_not_admin(self):
        with tempfile.TemporaryDirectory() as tmp:
            code, out, err, run = call(["install", "--vid", "1234", "--pid", "0001", "--driver", "winusb", "--wdi", fake_wdi(tmp), "--yes"])
            self.assertEqual(code, 3)
            self.assertEqual(run.mutating(), [])
            self.assertIn("Administrator", err)

    def test_not_admin_explains_how_to_elevate(self):
        code, out, err, run = call(["restore", "--vid", "0483", "--pid", "374B", "--iface", "0", "--yes"])
        self.assertEqual(code, 3)
        self.assertIn("Run as administrator", err)

    def test_dry_run_warns_when_not_elevated(self):
        code, out, err, run = call(["restore", "--vid", "0483", "--pid", "374B", "--iface", "0", "--dry-run"], admin=False)
        self.assertEqual(code, 0)
        self.assertIn("NOT elevated", out)
        code, out, err, run = call(["restore", "--vid", "0483", "--pid", "374B", "--iface", "0", "--dry-run"], admin=True)
        self.assertNotIn("NOT elevated", out)

    def test_protected_class(self):
        with tempfile.TemporaryDirectory() as tmp:
            argv = ["install", "--vid", "093A", "--pid", "2510", "--driver", "winusb", "--wdi", fake_wdi(tmp), "--dry-run"]
            code, out, err, run = call(argv)
            self.assertEqual(code, 2)
            self.assertIn("--force", err)
            self.assertEqual(call(argv + ["--force"])[0], 0)

    def test_warning_text(self):
        code, out, err, run = call(["install", "--vid", "1234", "--pid", "0001", "--driver", "winusb", "--dry-run"])
        for needle in ("SELF-SIGNED", "TrustedPublisher", "Administrator", "cert-remove"):
            self.assertIn(needle, out)

    def test_extract_flag_never_passed(self):
        with tempfile.TemporaryDirectory() as tmp:
            run = FakeRun()
            call(["install", "--vid", "1234", "--pid", "0001", "--driver", "winusb", "--wdi", fake_wdi(tmp), "--yes"], run=run, admin=True)
            for c in run.mutating():
                self.assertNotIn("-x", c)
                self.assertNotIn("--extract", c)


