class TestDiagnose(unittest.TestCase):
    SETUPAPI = "\n".join([
        ">>>  [Device Install (Hardware initiated) - USB\\VID_0416&PID_9391\\B]",
        ">>>  Section start 2026/10/10 09:00:00.000",
        "     dvi: Class GUID of device changed",
        "!!!  dvi: Device not started: Device has problem: 0x0a: CM_PROB_FAILED_START.",
        "<<<  Section end 2026/10/10 09:00:01.000",
        ">>>  [Device Install (Hardware initiated) - USB\\VID_1111&PID_2222\\C]",
        ">>>  Section start 2026/10/10 09:05:00.000",
        "     unrelated",
        "<<<  Section end 2026/10/10 09:05:01.000",
        ">>>  [Device Install (Hardware initiated) - USB\\VID_0416&PID_9391\\B]",
        ">>>  Section start 2026/10/12 18:00:00.000",
        "!!!  dvi: second failure",
        "<<<  Section end 2026/10/12 18:00:01.000",
    ])

    def test_codes(self):
        self.assertIn("FAILED_START", diagnose.describe_cm_code(10))
        self.assertIn("not installed", diagnose.describe_cm_code(28))
        self.assertIn("reported a problem", diagnose.describe_cm_code(43))
        self.assertIn("signature", diagnose.describe_cm_code(52))
        self.assertIn("not in the table", diagnose.describe_cm_code(999))
        self.assertIn("STATUS_UNSUCCESSFUL", diagnose.describe_ntstatus(3221225473))
        self.assertEqual(diagnose.describe_ntstatus(None), "-")

    def test_since(self):
        now = datetime(2026, 10, 10, 12, 0)
        self.assertEqual(diagnose.parse_since("2h", now), datetime(2026, 10, 10, 10, 0))
        self.assertEqual(diagnose.parse_since("7d", now), datetime(2026, 10, 3, 12, 0))
        self.assertEqual(diagnose.parse_since("2026-10-01"), datetime(2026, 10, 1))
        with self.assertRaises(ValueError):
            diagnose.parse_since("yesterday")

    def test_sections(self):
        devs = devices.parse_device_list(json.dumps(DEVICES))
        dev = devices.select_target(devs, 0x416, 0x9391)
        secs = diagnose.relevant_sections(self.SETUPAPI, dev)
        self.assertEqual(len(secs), 2)                               # the unrelated one is excluded
        self.assertEqual(len(diagnose.relevant_sections(self.SETUPAPI, dev, last=1)), 1)
        newer = diagnose.relevant_sections(self.SETUPAPI, dev, since=datetime(2026, 10, 11))
        self.assertEqual(len(newer), 1)
        self.assertIn("second failure", "\n".join(newer[0]["lines"]))

    def test_command_text_and_json(self):
        code, out, err, run = call(["diagnose", "--vid", "0416", "--pid", "9391", "--no-events"], setupapi_text=self.SETUPAPI)
        self.assertEqual(code, 0, err)
        self.assertIn("FAILED_START", out)
        self.assertIn("STATUS_UNSUCCESSFUL", out)
        self.assertIn("CM_PROB_FAILED_START", out)
        code, out, err, run = call(["diagnose", "--vid", "0416", "--pid", "9391", "--json"], setupapi_text=self.SETUPAPI)
        data = json.loads(out)
        self.assertEqual(data["data"]["problem"]["code"], 10)
        self.assertEqual(len(data["data"]["setupapi_sections"]), 2)
        self.assertEqual(run.mutating(), [])

    def test_all_devices_with_problems(self):
        code, out, err, run = call(["diagnose"])
        self.assertEqual(code, 0)
        self.assertIn("VID_1234&PID_0001", out)
        self.assertIn("VID_0416&PID_9391", out)
        self.assertNotIn("VID_AAAA", out)

    def test_missing_setupapi_is_not_fatal(self):
        code, out, err, run = call(["diagnose", "--vid", "0416", "--pid", "9391", "--no-events", "--setupapi", "/nonexistent/x.log"])
        self.assertEqual(code, 0)
        self.assertIn("cannot read", out)


