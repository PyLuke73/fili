class TestConfig(unittest.TestCase):
    def test_sample_is_valid(self):
        with tempfile.TemporaryDirectory() as tmp:
            p = os.path.join(tmp, "usbdrv.toml")
            write_text(p, config.SAMPLE)
            cfg = config.load_config(p, {})
            self.assertEqual(cfg["driver"]["default_driver"], "winusb")

    def test_errors(self):
        with tempfile.TemporaryDirectory() as tmp:
            p = os.path.join(tmp, "bad.toml")
            write_text(p, "[general]\nnope = 1\n")
            with self.assertRaises(config.ConfigError):
                config.load_config(p, {})
            with self.assertRaises(config.ConfigError):
                config.load_config(os.path.join(tmp, "missing.toml"), {})
            self.assertEqual(call(["list", "--config", p])[0], 2)

    def test_search_order(self):
        with tempfile.TemporaryDirectory() as tmp:
            write_text(os.path.join(tmp, "usbdrv.toml"), '[device]\nonly_no_driver = true\n')
            self.assertTrue(config.load_config(None, {}, cwd=tmp)["device"]["only_no_driver"])
            self.assertFalse(config.load_config(None, {}, cwd=os.path.join(tmp, "nope"))["device"]["only_no_driver"])

    def test_config_cannot_confirm(self):
        with tempfile.TemporaryDirectory() as tmp:
            p = os.path.join(tmp, "x.toml")
            write_text(p, "[general]\nyes = true\n")
            self.assertEqual(call(["list", "--config", p])[0], 2)

    def test_cli_overrides_config(self):
        with tempfile.TemporaryDirectory() as tmp:
            p = os.path.join(tmp, "x.toml")
            write_text(p, "[device]\nonly_no_driver = true\n")
            code, out, err, run = call(["list", "--config", p])
            self.assertEqual(len([l for l in out.splitlines() if ":" in l and l[0] != "V"]), 1)
            code, out, err, run = call(["list", "--config", p, "--no-only-no-driver"])
            self.assertGreater(len(out.splitlines()), 3)


