class TestHelp(unittest.TestCase):
    def _parsers(self):
        main = cli._build_parser()
        subs = [a for a in main._actions if a.__class__.__name__ == "_SubParsersAction"][0].choices
        return main, subs

    def test_every_command_has_examples(self):
        main, subs = self._parsers()
        self.assertIn("Examples", main.format_help())
        self.assertGreaterEqual(len(subs), 10)
        for name, sp in subs.items():
            text = sp.format_help()
            self.assertIn("Examples", text, name)
            self.assertIn("usbdrv", text.split("Examples", 1)[1], name)

    def test_examples_use_generic_ids_only(self):
        main, subs = self._parsers()
        texts = [main.format_help()] + [sp.format_help() for sp in subs.values()]
        for text in texts:
            for forbidden in ("0483", "374B", "374b", "nucleo", "st-link", "stlink", "stm32"):
                self.assertNotIn(forbidden, text.lower(), forbidden)

    def test_examples_parse_with_the_real_parser(self):
        # each example line that starts with "usbdrv" must be accepted by the parser
        import re
        import shlex
        main, subs = self._parsers()
        n = 0
        for text in [main.format_help()] + [sp.format_help() for sp in subs.values()]:
            for line in text.splitlines():
                m = re.match(r"\s+usbdrv\s+(.*)$", line)
                if not m or "<" in line or ">" in line or "Run '" in line:
                    continue
                cmdline = re.split(r"\s{3,}", m.group(1))[0]       # drop the trailing description
                try:
                    main.parse_args(shlex.split(cmdline, posix=False))
                except SystemExit:
                    self.fail("example does not parse: " + cmdline)
                n += 1
        self.assertGreater(n, 25)


